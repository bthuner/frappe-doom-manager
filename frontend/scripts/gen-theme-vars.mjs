#!/usr/bin/env node
/**
 * Emit the CSS custom properties that frappe-ui's semantic colour tokens read.
 *
 * The tailwind preset compiles `bg-surface-white` to
 * `var(--surface-white, #FFFFFF)` but never defines `--surface-white` anywhere:
 * inside Frappe's desk those variables come from the desk's own stylesheet, and
 * a standalone frappe-ui app like this one has to supply them. Without them
 * every token silently falls back to its light value, so setting
 * `data-theme="dark"` on <html> would change nothing.
 *
 * frappe-ui does ship the data, in tailwind/colors.json: `themedVariables.light`
 * and `.dark` map each token to a path into the colour primitives. Resolving
 * those here means the dark palette stays in step with frappe-ui across
 * upgrades instead of being a copied-out list of hex codes.
 *
 * Run by the `predev` / `prebuild` npm hooks; the output is committed so a bare
 * `vite build` still works.
 */
import { writeFileSync, readFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const colorsPath = resolve(here, '../node_modules/frappe-ui/tailwind/colors.json')
const outPath = resolve(here, '../src/theme-variables.css')

const colors = JSON.parse(readFileSync(colorsPath, 'utf-8'))

/** "lightMode/gray/200" -> "#E2E2E2" */
function lookup(path) {
  const value = path.split('/').reduce((node, key) => node?.[key], colors)
  if (typeof value !== 'string') {
    throw new Error(`Unresolved colour reference "${path}" in colors.json`)
  }
  return value
}

function declarations(mode) {
  const themed = colors.themedVariables[mode]
  if (!themed) throw new Error(`colors.json has no themedVariables.${mode}`)

  return Object.entries(themed)
    .flatMap(([category, tokens]) =>
      Object.entries(tokens).map(
        ([name, ref]) => `  --${category}-${name}: ${lookup(ref)};`,
      ),
    )
    .sort()
    .join('\n')
}

const light = declarations('light')
const dark = declarations('dark')

const css = `/*
 * GENERATED by scripts/gen-theme-vars.mjs -- do not edit.
 * Regenerate with \`npm run gen:theme\` (also runs before dev and build).
 * Source: frappe-ui/tailwind/colors.json (themedVariables).
 */

:root,
[data-theme='light'] {
${light}
}

[data-theme='dark'] {
${dark}
}
`

mkdirSync(dirname(outPath), { recursive: true })
writeFileSync(outPath, css)

const count = light.split('\n').length
console.log(`gen-theme-vars: wrote ${count} tokens x 2 themes to src/theme-variables.css`)
